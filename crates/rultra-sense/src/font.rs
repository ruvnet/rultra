//! A minimal 5x7 column-major font, enough for status text on an 8x8 panel.
//!
//! Column-major because scrolling is a horizontal shift: with one byte per
//! column, advancing the display is `pop_front`, not a per-pixel rotation.

/// Columns for one glyph. Bit 0 is the top row.
pub fn glyph(c: char) -> &'static [u8] {
    match c.to_ascii_uppercase() {
        'A' => &[0x7E, 0x11, 0x11, 0x11, 0x7E],
        'B' => &[0x7F, 0x49, 0x49, 0x49, 0x36],
        'C' => &[0x3E, 0x41, 0x41, 0x41, 0x22],
        'D' => &[0x7F, 0x41, 0x41, 0x22, 0x1C],
        'E' => &[0x7F, 0x49, 0x49, 0x49, 0x41],
        'F' => &[0x7F, 0x09, 0x09, 0x09, 0x01],
        'G' => &[0x3E, 0x41, 0x49, 0x49, 0x7A],
        'H' => &[0x7F, 0x08, 0x08, 0x08, 0x7F],
        'I' => &[0x00, 0x41, 0x7F, 0x41, 0x00],
        'J' => &[0x20, 0x40, 0x41, 0x3F, 0x01],
        'K' => &[0x7F, 0x08, 0x14, 0x22, 0x41],
        'L' => &[0x7F, 0x40, 0x40, 0x40, 0x40],
        'M' => &[0x7F, 0x02, 0x0C, 0x02, 0x7F],
        'N' => &[0x7F, 0x04, 0x08, 0x10, 0x7F],
        'O' => &[0x3E, 0x41, 0x41, 0x41, 0x3E],
        'P' => &[0x7F, 0x09, 0x09, 0x09, 0x06],
        'Q' => &[0x3E, 0x41, 0x51, 0x21, 0x5E],
        'R' => &[0x7F, 0x09, 0x19, 0x29, 0x46],
        'S' => &[0x46, 0x49, 0x49, 0x49, 0x31],
        'T' => &[0x01, 0x01, 0x7F, 0x01, 0x01],
        'U' => &[0x3F, 0x40, 0x40, 0x40, 0x3F],
        'V' => &[0x1F, 0x20, 0x40, 0x20, 0x1F],
        'W' => &[0x7F, 0x20, 0x18, 0x20, 0x7F],
        'X' => &[0x63, 0x14, 0x08, 0x14, 0x63],
        'Y' => &[0x03, 0x04, 0x78, 0x04, 0x03],
        'Z' => &[0x61, 0x51, 0x49, 0x45, 0x43],
        '0' => &[0x3E, 0x51, 0x49, 0x45, 0x3E],
        '1' => &[0x00, 0x42, 0x7F, 0x40, 0x00],
        '2' => &[0x42, 0x61, 0x51, 0x49, 0x46],
        '3' => &[0x21, 0x41, 0x45, 0x4B, 0x31],
        '4' => &[0x18, 0x14, 0x12, 0x7F, 0x10],
        '5' => &[0x27, 0x45, 0x45, 0x45, 0x39],
        '6' => &[0x3C, 0x4A, 0x49, 0x49, 0x30],
        '7' => &[0x01, 0x71, 0x09, 0x05, 0x03],
        '8' => &[0x36, 0x49, 0x49, 0x49, 0x36],
        '9' => &[0x06, 0x49, 0x49, 0x29, 0x1E],
        '.' => &[0x00, 0x60, 0x60, 0x00, 0x00],
        ':' => &[0x00, 0x36, 0x36, 0x00, 0x00],
        '-' => &[0x08, 0x08, 0x08, 0x08, 0x08],
        '!' => &[0x00, 0x00, 0x5F, 0x00, 0x00],
        '?' => &[0x02, 0x01, 0x51, 0x09, 0x06],
        '*' => &[0x14, 0x08, 0x3E, 0x08, 0x14],
        '+' => &[0x08, 0x08, 0x3E, 0x08, 0x08],
        '%' => &[0x63, 0x13, 0x08, 0x64, 0x63],
        _ => &[0x00, 0x00, 0x00, 0x00, 0x00], // space and anything unmapped
    }
}

/// Render text to a column buffer, one blank column between glyphs, with eight
/// blank columns of lead-in and lead-out so the message scrolls fully on and
/// fully off the panel.
pub fn columns(text: &str) -> Vec<u8> {
    let mut out = vec![0u8; 8];
    for c in text.chars() {
        out.extend_from_slice(glyph(c));
        out.push(0x00);
    }
    out.extend_from_slice(&[0u8; 8]);
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn every_glyph_is_five_columns() {
        for c in "ABCXYZ0189.:-!?*+% ".chars() {
            assert_eq!(glyph(c).len(), 5, "{c:?} is not 5 columns");
        }
    }

    #[test]
    fn unmapped_characters_render_blank_rather_than_panicking() {
        assert_eq!(glyph('\u{263A}'), &[0, 0, 0, 0, 0]);
    }

    #[test]
    fn text_is_padded_so_it_scrolls_on_and_off() {
        let c = columns("A");
        assert_eq!(&c[..8], &[0u8; 8], "missing lead-in");
        assert_eq!(&c[c.len() - 8..], &[0u8; 8], "missing lead-out");
        // 8 lead-in + 5 glyph + 1 gap + 8 lead-out
        assert_eq!(c.len(), 22);
    }

    #[test]
    fn lowercase_maps_to_the_same_glyph_as_uppercase() {
        assert_eq!(glyph('a'), glyph('A'));
    }
}
